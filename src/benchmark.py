@dataclass
class BenchmarkRow:
    """Holds summary evaluation metrics for one agent on a benchmark suite.

    Attributes:
        agent_name: Display label for the agent (e.g. 'Baseline Agent', 'Advanced Agent').
        agent_tokens_only: Cumulative tokens generated by the assistant during conversation.
        prompt_tokens_processed: Cumulative context tokens fed into the model prompt across turns.
        recall_score: Cross-session fact retrieval accuracy (0.0 to 1.0).
        response_quality: Heuristic evaluation score balancing recall and substance (0.0 to 1.0).
        memory_growth_bytes: Total persistent memory storage size in bytes on disk.
        compactions: Number of thread context compaction events executed.
    """

    agent_name: str
    agent_tokens_only: int
    prompt_tokens_processed: int
    recall_score: float
    response_quality: float
    memory_growth_bytes: int
    compactions: int


def load_conversations(path: Path) -> list[dict[str, Any]]:
    """Read and deserialize JSON conversation benchmark data from disk.

    Args:
        path: Path to the JSON dataset file.

    Returns:
        List of conversation dictionaries containing turns and recall questions.

    Raises:
        FileNotFoundError: If the specified file path does not exist.
    """
    if not path.exists():
        raise FileNotFoundError(f"Dataset file not found at: {path}")
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data if isinstance(data, list) else [data]


def recall_points(answer: str, expected: list[str]) -> float:
    """Calculate the fraction of expected fact strings present in the agent response.

    Case-insensitive matching of each item in `expected` within `answer`.

    Args:
        answer: Response text string produced by the agent.
        expected: List of target fact keywords/phrases required to be recalled.

    Returns:
        Float score between 0.0 (no facts matched) and 1.0 (all facts matched).
    """
    if not expected:
        return 1.0
    ans_lower = answer.lower()
    matches = sum(1 for exp in expected if exp.lower() in ans_lower)
    return round(matches / len(expected), 2)


def heuristic_quality(answer: str, expected: list[str]) -> float:
    """Compute a lightweight heuristic quality score for offline evaluation.

    Weights recall accuracy at 80% and response substance/completeness at 20%.

    Args:
        answer: Response text string produced by the agent.
        expected: List of target fact keywords/phrases.

    Returns:
        Float score between 0.0 and 1.0.
    """
    recall = recall_points(answer, expected)
    ans_stripped = answer.strip()
    substance_bonus = 0.2 if len(ans_stripped) >= 15 else 0.1
    quality = recall * 0.8 + substance_bonus
    return round(min(1.0, quality), 2)


def run_agent_benchmark(
    agent_name: str,
    agent: Any,
    conversations: list[dict[str, Any]],
    config: Any,
) -> BenchmarkRow:
    """Execute a full benchmark evaluation suite for a single agent.

    Workflow:
        1. Feeds conversational turns sequentially to the agent within their session thread.
        2. Queries recall questions in an isolated fresh thread to evaluate cross-session retention.
        3. Measures token consumption, prompt load, recall precision, and compaction triggers.

    Args:
        agent_name: Human-readable name of the agent.
        agent: Agent instance (BaselineAgent or AdvancedAgent).
        conversations: List of benchmark conversation fixtures.
        config: LabConfig configuration instance.

    Returns:
        BenchmarkRow populated with aggregated evaluation metrics.
    """
    recall_scores: list[float] = []
    quality_scores: list[float] = []
    user_ids: set[str] = set()

    for conv in conversations:
        conv_id = conv.get("id", "conv")
        user_id = conv.get("user_id", "default_user")
        user_ids.add(user_id)
        turns = conv.get("turns", [])
        recall_questions = conv.get("recall_questions", [])

        # Feed turns within same thread
        for turn in turns:
            agent.reply(user_id=user_id, thread_id=conv_id, message=turn)

        # Test recall questions in a fresh thread
        for q_idx, q in enumerate(recall_questions):
            fresh_thread = f"{conv_id}_recall_{q_idx}"
            question_text = q.get("question", "")
            expected = q.get("expected_contains", [])

            reply_out = agent.reply(user_id=user_id, thread_id=fresh_thread, message=question_text)
            answer = reply_out.get("response", "")

            pts = recall_points(answer, expected)
            qual = heuristic_quality(answer, expected)
            recall_scores.append(pts)
            quality_scores.append(qual)

    avg_recall = sum(recall_scores) / len(recall_scores) if recall_scores else 0.0
    avg_quality = sum(quality_scores) / len(quality_scores) if quality_scores else 0.0

    # Calculate memory file growth
    total_mem_bytes = 0
    if hasattr(agent, "memory_file_size"):
        for uid in user_ids:
            total_mem_bytes += agent.memory_file_size(uid)

    total_compactions = agent.compaction_count() if hasattr(agent, "compaction_count") else 0

    return BenchmarkRow(
        agent_name=agent_name,
        agent_tokens_only=agent.token_usage(),
        prompt_tokens_processed=agent.prompt_token_usage(),
        recall_score=round(avg_recall, 2),
        response_quality=round(avg_quality, 2),
        memory_growth_bytes=total_mem_bytes,
        compactions=total_compactions,
    )


def format_rows(rows: list[BenchmarkRow]) -> str:
    """Format benchmark result rows into a GitHub-flavored Markdown table.

    Args:
        rows: List of BenchmarkRow records to format.

    Returns:
        Formatted string containing Markdown table.
    """
    headers = [
        "Agent",
        "Agent tokens only",
        "Prompt tokens processed",
        "Cross-session recall",
        "Response quality",
        "Memory growth (bytes)",
        "Compactions",
    ]
    table_data = []
    for r in rows:
        table_data.append([
            r.agent_name,
            f"{r.agent_tokens_only:,}",
            f"{r.prompt_tokens_processed:,}",
            f"{r.recall_score * 100:.1f}%",
            f"{r.response_quality * 100:.1f}%",
            f"{r.memory_growth_bytes:,} B",
            r.compactions,
        ])
    return tabulate(table_data, headers=headers, tablefmt="github")


def main() -> None:
    """Entrypoint to run both Standard and Long-Context Stress benchmarks and print comparison tables."""
    config = load_config(Path(__file__).resolve().parent.parent)

    std_path = config.data_dir / "conversations.json"
    stress_path = config.data_dir / "advanced_long_context.json"

    std_convs = load_conversations(std_path)
    stress_convs = load_conversations(stress_path)

    print("\n" + "=" * 80)
    print("### 1. STANDARD BENCHMARK (data/conversations.json)")
    print("=" * 80)

    # 1. Baseline Agent on Standard
    base_std = BaselineAgent(config, force_offline=True)
    row_base_std = run_agent_benchmark("Baseline Agent", base_std, std_convs, config)

    # 2. Advanced Agent on Standard (isolated state directory)
    adv_cfg_std = load_config(config.base_dir)
    adv_cfg_std.state_dir = config.base_dir / "state" / "benchmark_std"
    adv_cfg_std.state_dir.mkdir(parents=True, exist_ok=True)
    (adv_cfg_std.state_dir / "profiles").mkdir(parents=True, exist_ok=True)

    adv_std = AdvancedAgent(adv_cfg_std, force_offline=True)
    row_adv_std = run_agent_benchmark("Advanced Agent", adv_std, std_convs, adv_cfg_std)

    print(format_rows([row_base_std, row_adv_std]))

    print("\n" + "=" * 80)
    print("### 2. LONG-CONTEXT STRESS BENCHMARK (data/advanced_long_context.json)")
    print("=" * 80)

    # 1. Baseline Agent on Stress
    base_stress = BaselineAgent(config, force_offline=True)
    row_base_stress = run_agent_benchmark("Baseline Agent", base_stress, stress_convs, config)

    # 2. Advanced Agent on Stress (isolated state directory)
    adv_cfg_stress = load_config(config.base_dir)
    adv_cfg_stress.state_dir = config.base_dir / "state" / "benchmark_stress"
    adv_cfg_stress.state_dir.mkdir(parents=True, exist_ok=True)
    (adv_cfg_stress.state_dir / "profiles").mkdir(parents=True, exist_ok=True)

    adv_stress = AdvancedAgent(adv_cfg_stress, force_offline=True)
    row_adv_stress = run_agent_benchmark("Advanced Agent", adv_stress, stress_convs, adv_cfg_stress)

    print(format_rows([row_base_stress, row_adv_stress]))
    print("=" * 80 + "\n")


if __name__ == "__main__":
    main()
